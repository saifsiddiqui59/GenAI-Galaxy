'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const js=fs.readFileSync(path.join(__dirname,'../../galaxy/handoff/planet-flight.js'),'utf8');
let created=[];
const body={appendChild:e=>created.push(e)};
const document={body,createElement:()=>({style:{},setAttribute(){},animate(){return {finished:Promise.resolve(),cancel(){}}},remove(){this.removed=true}})};
const window={document,matchMedia:()=>({matches:false})};
vm.runInNewContext(js,{window,Math,Number,Promise}, {filename:'planet-flight.js'});
const api=window.GalaxyPlanetHandoff;
const sourceRect={left:100,top:120,width:60,height:60};
const targetRect={left:350,top:260,width:70,height:70};
assert.equal(api.validRect(sourceRect),true);
assert.equal(api.validRect({left:0,top:0,width:-1,height:2}),false);
assert.equal(api.frames(sourceRect,targetRect).length,3);
(async()=>{
 let navigated=0;
 const result=await api.run({sourceRect,targetRect,onNavigate:()=>navigated++});
 assert.equal(result.reason,'completed');
 assert.equal(result.animated,true);
 assert.equal(navigated,1);
 assert.equal(created.length,1);
 assert.equal(created[0].removed,true);
 const missing=await api.run({sourceRect,onNavigate:()=>navigated++});
 assert.equal(missing.reason,'missing-anchor');
 assert.equal(navigated,2);
 const motion=await api.run({sourceRect,targetRect,motion:false,onNavigate:()=>navigated++});
 assert.equal(motion.reason,'reduced-motion');assert.equal(navigated,3);
 const abort=await api.run({sourceRect,targetRect,signal:{aborted:true},onNavigate:()=>navigated++});
 assert.equal(abort.reason,'aborted');assert.equal(navigated,4);
 const errorDoc={body,createElement:()=>({style:{},setAttribute(){},animate(){throw Error('GPU unavailable')},remove(){this.removed=true}})};
 const bad=await api.run({document:errorDoc,sourceRect,targetRect,onNavigate:()=>navigated++});
 assert.equal(bad.reason,'animation-error');assert.equal(navigated,5);
 console.log('Galaxy two-hand planet handoff: async, fallback, reduced motion, cancellation PASS');
})().catch(e=>{console.error(e);process.exitCode=1});
