const assert=require('node:assert/strict');
const p=require('../features/saas-operations.js');
const now=Date.parse('2026-10-24T00:00:00Z');
const later=days=>new Date(now+days*86400000).toISOString();
assert.equal(p.renewal({plan_code:'FREE',status:'ACTIVE'},now),null);
assert.equal(p.renewal({plan_code:'PRO',status:'ACTIVE',expires_at:later(40)},now),null);
assert.equal(p.renewal({plan_code:'PRO',status:'ACTIVE',expires_at:later(20)},now).level,'info');
assert.equal(p.renewal({plan_code:'PLUS',status:'ACTIVE',expires_at:later(10)},now).level,'attention');
assert.equal(p.renewal({plan_code:'PRO',status:'ACTIVE',expires_at:later(1)},now).level,'critical');
assert.match(p.renewal({plan_code:'PRO',status:'SUSPENDED'},now).message,/restricted/);
assert.match(p.renewal({plan_code:'PRO',status:'ACTIVE',expires_at:later(-2)},now).title,/expired/i);
const summary={accounts:12,pending:2,approved:6,active_subscriptions:4,suspended:1,expiring_in_7_days:2,expired_or_past_due:1,ai_evaluations_today:42,ai_global_daily_cap:50};
const warnings=p.warnings(summary);
assert.ok(warnings.some(a=>a.title.includes('pending approvals')));
assert.ok(warnings.some(a=>a.title.includes('AI usage')));
assert.ok(warnings.some(a=>a.title.includes('unverified')||a.message.includes('unverified')));
assert.equal(p.warnings({},false)[0].title,'Incomplete monitoring');
assert.equal(p.warnings(null,true)[0].title,'Monitoring unavailable');
console.log('P37 free plan renewal and SaaS alert tests passed');
